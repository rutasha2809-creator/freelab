paymentForm.addEventListener('submit', async e => {
  e.preventDefault();
  const id = document.getElementById('paymentId').value;
  const clientId = document.getElementById('paymentClient').value;
  const task = document.getElementById('paymentTask').value.trim();
  const amount = Number(document.getElementById('paymentAmount').value) || 0;
  const planDate = document.getElementById('paymentPlanDate').value;
  const factDate = document.getElementById('paymentFactDate').value || null;
  const factAmountRaw = document.getElementById('paymentFactAmount').value;
  // Фактическая сумма имеет смысл только у оплаченной записи; пустое поле —
  // значит получено ровно столько, сколько планировалось
  const factAmount = factDate && factAmountRaw !== '' ? Number(factAmountRaw) : null;
  if (!clientId || clientId === NEW_CLIENT_OPTION || !task || !planDate) return;

  // Признак «создано планировщиком» сохраняем: иначе отредактированная запись
  // становится «ручной», планировщик перестаёт её видеть и создаёт дубль
  const prev = id ? state.payments.find(x => x.id === id) : null;
  const draft = { clientId, task, amount, planDate, factDate, factAmount,
                  autoGenerated: prev ? !!prev.autoGenerated : false };
  const row = paymentToRow(draft);

  const wasPaid = id ? !!state.payments.find(x => x.id === id)?.factDate : false;

  try {
    if (id) {
      const { error } = await sb.from('payments').update(row).eq('id', id);
      if (error) throw error;
      Object.assign(state.payments.find(x => x.id === id), draft);
    } else {
      const { data, error } = await sb.from('payments').insert(row).select().single();
      if (error) throw error;
      state.payments.push(rowToPayment(data));
    }
    closeModals();
    renderAll();
    // Салют — на момент, когда деньги действительно отмечены полученными
    if (factDate && !wasPaid) celebrateAt(window.innerWidth / 2, window.innerHeight * 0.4);
    showToast(id ? t('Запись обновлена') : t('Запись добавлена'));
    // Заплатили меньше плана — предлагаем не потерять остаток. Спрашиваем один раз:
    // при повторном сохранении с той же суммой окно не всплывает снова
    const prevFact = prev ? prev.factAmount : null;
    if (factDate && factAmount != null && factAmount < amount && (!wasPaid || prevFact !== factAmount)) {
      openRemainderModal({ clientId, task, rest: amount - factAmount });
    }
  } catch (err) {
    console.error(err);
    showToast(t('Не удалось сохранить запись'));
  }
});

