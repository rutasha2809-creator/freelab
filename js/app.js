function overallSparklineSVG() {
  const now = new Date();
  const keys = [];
  for (let i = 5; i >= 0; i--) {
    const d = new Date(now.getFullYear(), now.getMonth() - i, 1);
    keys.push(`${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}`);
  }
  const byKey = Object.fromEntries(keys.map(k => [k, 0]));
  state.payments.forEach(p => {
    if (!p.factDate || !inView(p)) return;
    const key = monthGroupKey(p.factDate);
    if (key in byKey) byKey[key] += amountOf(p);
  });
  const values = keys.map(k => byKey[k]);
  if (values.filter(v => v > 0).length < 2) return '';

  const w = 260, h = 46, pad = 3;
  const max = Math.max(...values, 1);
  const stepX = (w - pad * 2) / (values.length - 1);
  const points = values.map((v, i) => [
    pad + i * stepX,
    h - pad - (v / max) * (h - pad * 2),
  ]);
  const path = points.map((p, i) => (i === 0 ? 'M' : 'L') + p[0].toFixed(1) + ',' + p[1].toFixed(1)).join(' ');
  // Линия с растворяющейся заливкой под ней — мягче, чем голый штрих
  return `
    <defs>
      <linearGradient id="sparkFill" x1="0" y1="0" x2="0" y2="1">
        <stop offset="0%" stop-color="#ffffff" stop-opacity="0.34"/>
        <stop offset="100%" stop-color="#ffffff" stop-opacity="0"/>
      </linearGradient>
    </defs>
    <path d="${path} L${w},${h} L0,${h} Z" fill="url(#sparkFill)"/>
    <path d="${path}" fill="none" stroke="rgba(255,255,255,.8)" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"/>
  `;
}

