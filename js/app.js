function avatarInitials(name, email) {
  const source = (name || (email || '').split('@')[0] || '').trim();
  if (!source) return '·';
  const parts = source.split(/[\s._-]+/).filter(Boolean).slice(0, 2);
  const initials = parts.map(w => w[0]).join('');
  return (initials || source[0]).toUpperCase();
}

