const introCtl = (function () {
  const intro = document.getElementById('intro');
  if (!intro) return { play() {}, stop() {} };
  const scenes = [...intro.querySelectorAll('.iScene')];
  const segs = [...intro.querySelectorAll('.introBar span')];
  const DUR = [5200, 5000, 5400, 7000]; // вдвое медленнее; последняя дольше — рука рисуется долго
  let idx = -1, timer = null, running = false;

  function stop() {
    if (!running) return;
    running = false;
    clearTimeout(timer); timer = null;
    document.removeEventListener('keydown', onKey);
    intro.classList.add('is-done');
    setTimeout(() => { intro.hidden = true; intro.classList.remove('is-done'); }, 700);
  }
  function show(n) {
    if (n >= scenes.length) { stop(); return; }
    idx = n;
    scenes.forEach((s, k) => s.classList.toggle('is-on', k === n));
    segs.forEach((s, k) => {
      s.classList.toggle('is-past', k < n);
      s.classList.remove('is-on');
    });
    // перезапуск перехода полосы: браузеру нужен кадр между сбросом и включением
    requestAnimationFrame(() => {
      if (!segs[n]) return;
      segs[n].style.setProperty('--t', DUR[n] + 'ms');
      segs[n].classList.add('is-on');
    });
    timer = setTimeout(() => show(n + 1), DUR[n]);
  }
  function onKey(e) { if (e.key === 'Escape' || e.key === ' ' || e.key === 'Enter') stop(); }

  intro.addEventListener('click', e => {
    if (e.target.closest('.introSkip')) { stop(); return; }
    clearTimeout(timer);
    show(idx + 1);
  });

  // Заставка идёт при каждом заходе на экран входа — пропустить можно кнопкой,
  // кликом или Esc. Не показываем только тем, кто просил ограничить анимацию.
  function play() {
    if (running || prefersReducedMotion) return;
    running = true;
    intro.hidden = false;
    intro.classList.remove('is-done');
    document.addEventListener('keydown', onKey);
    requestAnimationFrame(() => show(0));
  }
  return { play, stop };
})();

// Заставку показываем при каждом открытии сайта — и на экране входа, и когда
// сессия уже есть: она перекрывает всё собой, а под ней спокойно грузится приложение
introCtl.play();

function showApp(session) {
  authScreenEl.hidden = true;
  appEl.hidden = false;
  authForm.hidden = false;
  recoveryForm.hidden = true;
  applyUserIdentity(session);
  // Supabase может прислать несколько событий авторизации подряд (вход, обновление токена);
  // данные загружаем один раз на пользователя, а не при каждом таком событии
  if (loadedForUserId !== session.user.id) {
    loadedForUserId = session.user.id;
    dashboardMonthOffset = 0; // новый вход всегда начинается с текущего месяца
    lastAnimatedValues = {};  // и с чистого счёта для анимации сумм
    renderSkeleton();
    fetchState();
    maybeAskName(session);
  }
}

function showAuth() {
  appEl.hidden = true;
  authScreenEl.hidden = false;
  authForm.hidden = false;
  recoveryForm.hidden = true;
  authForm.reset();
  setAuthMode('signin');
}

function showRecovery() {
  appEl.hidden = true;
  authScreenEl.hidden = false;
  authForm.hidden = true;
  recoveryForm.hidden = false;
}

let recoveryMode = false;

sb.auth.onAuthStateChange((event, session) => {
  if (event === 'PASSWORD_RECOVERY') {
    recoveryMode = true;
    showRecovery();
    return;
  }
  if (recoveryMode) return;
  if (session) showApp(session);
  else { loadedForUserId = null; showAuth(); }
});

sb.auth.getSession().then(({ data }) => {
  if (recoveryMode) return;
  if (data.session) showApp(data.session);
  else showAuth();
});
