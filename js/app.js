function formatDateShort(iso) {
  if (!iso) return '—';
  const d = new Date(iso + 'T00:00:00');
  if (isNaN(d)) return '—';
  return d.toLocaleDateString('ru-RU', { day: 'numeric', month: 'short' });
}

function todayISO() {
  const d = new Date();
  return toISO(d);
}

function toISO(d) {
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${y}-${m}-${day}`;
}

// ---------- Автоматический график ожидаемых платежей ----------

const SCHEDULE_HORIZON_MONTHS = 6;

function daysInMonth(year, monthIndex) {
  return new Date(year, monthIndex + 1, 0).getDate();
}

// Дата в конкретном месяце с "прилипанием" ко дню (напр. 31 число в феврале -> последний день месяца)
function dateForDayInMonth(year, monthIndex, day) {
  const clamped = Math.min(day, daysInMonth(year, monthIndex));
  return toISO(new Date(year, monthIndex, clamped));
}

// Ближайшая дата >= fromISO, приходящаяся на нужный день недели (1=понедельник...7=воскресенье)
function firstWeekdayOnOrAfter(fromISO, isoWeekday) {
  const d = new Date(fromISO + 'T00:00:00');
  const currentIsoWeekday = d.getDay() === 0 ? 7 : d.getDay();
  const diff = (isoWeekday - currentIsoWeekday + 7) % 7;
  d.setDate(d.getDate() + diff);
  return toISO(d);
}

function addDaysISO(iso, days) {
  const d = new Date(iso + 'T00:00:00');
  d.setDate(d.getDate() + days);
  return toISO(d);
}

function addMonthsHorizonISO(fromISO, months) {
  const d = new Date(fromISO + 'T00:00:00');
  d.setMonth(d.getMonth() + months);
  return toISO(d);
}

// Считает ожидаемые начисления для клиента между fromISO и toISO (включительно) по данным его карточки
function computeScheduledOccurrences(client, fromISO, toISO_) {
  if (client.type !== 'recurring' || !client.planAmount) return [];
  const out = [];

  if (client.planFrequency === 'weekly') {
    if (!client.planWeekday) return out;
    let date = firstWeekdayOnOrAfter(fromISO, client.planWeekday);
    while (date <= toISO_) {
      out.push({ planDate: date, amount: client.planAmount, task: 'Еженедельный платёж' });
      date = addDaysISO(date, 7);
    }
    return out;
  }

  // Ежемесячно
  if (client.planDay) {
    const start = new Date(fromISO + 'T00:00:00');
    const end = new Date(toISO_ + 'T00:00:00');
    let y = start.getFullYear(), m = start.getMonth();
    const task = client.planAmount2 ? 'Аванс' : 'Плановый платёж';
    while (y < end.getFullYear() || (y === end.getFullYear() && m <= end.getMonth())) {
      const date = dateForDayInMonth(y, m, client.planDay);
      if (date >= fromISO && date <= toISO_) out.push({ planDate: date, amount: client.planAmount, task });
      m++;
      if (m > 11) { m = 0; y++; }
    }
  }
  if (client.planAmount2 && client.planDay2) {
    const start = new Date(fromISO + 'T00:00:00');
    const end = new Date(toISO_ + 'T00:00:00');
    let y = start.getFullYear(), m = start.getMonth();
    while (y < end.getFullYear() || (y === end.getFullYear() && m <= end.getMonth())) {
      const date = dateForDayInMonth(y, m, client.planDay2);
      if (date >= fromISO && date <= toISO_) out.push({ planDate: date, amount: client.planAmount2, task: 'Остаток' });
      m++;
      if (m > 11) { m = 0; y++; }
    }
  }
  return out;
}

// Дополняет график клиента недостающими автосозданными платежами на горизонт вперёд,
// не трогая уже существующие (в т.ч. добавленные вручную) записи.
async function syncClientSchedule(client) {
  if (client.type !== 'recurring' || !client.planAmount) return;
  const from = todayISO();
  const to = addMonthsHorizonISO(from, SCHEDULE_HORIZON_MONTHS);
  const occurrences = computeScheduledOccurrences(client, from, to);
  if (!occurrences.length) return;

  const existingKeys = new Set(
    state.payments
      .filter(p => p.clientId === client.id && p.autoGenerated)
      .map(p => `${p.planDate}|${p.task}`)
  );
  const toInsert = occurrences.filter(o => !existingKeys.has(`${o.planDate}|${o.task}`));
  if (!toInsert.length) return;

  const rows = toInsert.map(o => paymentToRow({
    clientId: client.id, task: o.task, amount: o.amount, planDate: o.planDate, factDate: null, autoGenerated: true,
  }));
  // upsert + ignoreDuplicates: если та же запись (клиент/дата/тип) уже есть в базе
  // (например, из-за параллельной загрузки), она просто не будет продублирована
  const { data, error } = await sb.from('payments')
    .upsert(rows, { onConflict: 'client_id,plan_date,task,auto_generated', ignoreDuplicates: true })
    .select();
  if (error) { console.error(error); return; }
  state.payments.push(...(data || []).map(rowToPayment));
}

async function syncAllSchedules() {
  for (const client of state.clients) {
    await syncClientSchedule(client);
  }
}

// Удаляет ещё не наступившие и не оплаченные автосозданные платежи клиента
// (используется перед пересборкой графика после изменения условий в карточке)
async function clearFutureAutoPayments(clientId) {
  const from = todayISO();
  const { error } = await sb.from('payments')
    .delete()
    .eq('client_id', clientId)
    .eq('auto_generated', true)
    .is('fact_date', null)
    .gte('plan_date', from);
  if (error) { console.error(error); return; }
  state.payments = state.payments.filter(p =>
    !(p.clientId === clientId && p.autoGenerated && !p.factDate && p.planDate >= from)
  );
}

