function firstDayOfMonth(d = new Date()) { return new Date(d.getFullYear(), d.getMonth(), 1); }
function lastDayOfMonth(d = new Date()) { return new Date(d.getFullYear(), d.getMonth() + 1, 0); }

function setReportPreset(preset) {
  const now = new Date();
  let from, to;
  if (preset === 'month') {
    from = firstDayOfMonth(now); to = lastDayOfMonth(now);
  } else if (preset === 'quarter') {
    const q = Math.floor(now.getMonth() / 3);
    from = new Date(now.getFullYear(), q * 3, 1);
    to = new Date(now.getFullYear(), q * 3 + 3, 0);
  } else if (preset === 'year') {
    from = new Date(now.getFullYear(), 0, 1);
    to = new Date(now.getFullYear(), 11, 31);
  } else {
    const dates = state.payments.map(p => p.factDate).filter(Boolean).sort();
    from = dates.length ? new Date(dates[0] + 'T00:00:00') : firstDayOfMonth(now);
    to = now;
  }
  document.getElementById('reportFrom').value = toISO(from);
  document.getElementById('reportTo').value = toISO(to);
  renderReports();
}

// Столбики дохода по месяцам за год. Одна серия — легенда не нужна,
// заголовок и так говорит, что показано. Подписываем только самый крупный месяц.
function monthlyIncomeChartSVG() {
  const now = new Date();
  // На узком экране двенадцать столбиков сжимаются так, что подписи становятся
  // нечитаемыми — показываем полгода и уже́ холст, тогда текст остаётся крупным
  const narrow = window.innerWidth < 640;
  const span = narrow ? 6 : 12;
  const months = [];
  for (let i = span - 1; i >= 0; i--) {
    const d = new Date(now.getFullYear(), now.getMonth() - i, 1);
    months.push({ year: d.getFullYear(), month: d.getMonth(), sum: 0 });
  }
  state.payments.forEach(p => {
    if (!p.factDate || !inView(p)) return;
    const d = new Date(p.factDate + 'T00:00:00');
    const slot = months.find(m => m.year === d.getFullYear() && m.month === d.getMonth());
    if (slot) slot.sum += amountOf(p);
  });
  if (!months.some(m => m.sum > 0)) return '';

  const W = narrow ? 360 : 720, H = narrow ? 190 : 210, padL = narrow ? 44 : 52, padR = 10, padT = 14, padB = 26;
  const plotW = W - padL - padR, plotH = H - padT - padB;
  const rawMax = Math.max(...months.map(m => m.sum));
  // Округляем верх шкалы до «круглого» числа, чтобы подписи оси читались
  const step = Math.pow(10, Math.floor(Math.log10(rawMax))) / 2;
  const max = Math.ceil(rawMax / step) * step || 1;

  const band = plotW / months.length;
  const barW = Math.min(24, band - 10);          // столбик не заполняет всю полосу
  const maxIdx = months.reduce((b, m, i) => (m.sum > months[b].sum ? i : b), 0);

  const ticks = [0, max / 2, max].map(v => {
    const y = padT + plotH - (v / max) * plotH;
    return `<line x1="${padL}" y1="${y.toFixed(1)}" x2="${W - padR}" y2="${y.toFixed(1)}"
                  stroke="var(--line)" stroke-width="1"/>
            <text x="${padL - 8}" y="${(y + 3.5).toFixed(1)}" text-anchor="end"
                  class="chartTick">${new Intl.NumberFormat(LOCALE).format(Math.round(v))}</text>`;
  }).join('');

  const bars = months.map((m, i) => {
    const h = m.sum > 0 ? Math.max(3, (m.sum / max) * plotH) : 0;
    const x = padL + i * band + (band - barW) / 2;
    const y = padT + plotH - h;
    const label = `${MONTHS_NOM[m.month]} ${m.year} — ${formatMoney(m.sum)}`;
    const bar = h > 0
      ? `<rect x="${x.toFixed(1)}" y="${y.toFixed(1)}" width="${barW.toFixed(1)}" height="${h.toFixed(1)}"
               rx="4" fill="var(--violet)"><title>${escapeHTML(label)}</title></rect>
         <rect x="${x.toFixed(1)}" y="${(padT + plotH - 4).toFixed(1)}" width="${barW.toFixed(1)}" height="4"
               fill="var(--violet)" pointer-events="none"/>`
      : `<rect x="${x.toFixed(1)}" y="${(padT + plotH - 2).toFixed(1)}" width="${barW.toFixed(1)}" height="2"
               rx="1" fill="var(--line)"><title>${escapeHTML(label)}</title></rect>`;
    const tip = (i === maxIdx && m.sum > 0)
      ? `<text x="${(x + barW / 2).toFixed(1)}" y="${(y - 6).toFixed(1)}" text-anchor="middle"
               class="chartValue">${formatMoney(m.sum)}</text>`
      : '';
    const name = `<text x="${(x + barW / 2).toFixed(1)}" y="${H - 8}" text-anchor="middle"
                        class="chartTick">${(LANG === 'en' ? MONTHS_NOM[m.month].slice(0, 3) : MONTHS_NOM[m.month].slice(0, 3).toLowerCase())}</text>`;
    return bar + tip + name;
  }).join('');

  return `<svg class="chart" viewBox="0 0 ${W} ${H}" role="img"
               aria-label="${t('Доход по месяцам за последние 12 месяцев')}">${ticks}${bars}</svg>`;
}

function renderReports() {
  const fromEl = document.getElementById('reportFrom');
  const toEl = document.getElementById('reportTo');
  if (!fromEl.value || !toEl.value) return;
  const from = fromEl.value, to = toEl.value;

  const payments = state.payments.filter(p => p.factDate && p.factDate >= from && p.factDate <= to && inView(p));

  let grossAll = 0, taxAll = 0;
  const byClient = new Map();
  for (const p of payments) {
    const c = getClient(p.clientId);
    if (!c) continue;
    const amount = amountOf(p);
    const rate = clientTaxRatePercent(c);
    const tax = amount * rate / 100;
    grossAll += amount; taxAll += tax;
    const agg = byClient.get(c.id) || { name: c.name, type: c.type, gross: 0, tax: 0 };
    agg.gross += amount; agg.tax += tax;
    byClient.set(c.id, agg);
  }
  const netAll = grossAll - taxAll;
  const noTax = taxSettings.mode === 'none';

  const everReceived = state.payments.some(p => p.factDate);

  document.getElementById('reportStats').innerHTML = `
    <div class="tile tile--dark">
      <div class="tile__label">${t('Получено за период')}</div>
      <div class="tile__value">${formatMoney(grossAll)}</div>
    </div>
    ${noTax ? '' : `<div class="tile">
      <div class="tile__label" style="color:var(--muted)">${taxName()}</div>
      <div class="tile__value">${formatMoney(taxAll)}</div>
    </div>
    <div class="tile">
      <div class="tile__label" style="color:var(--muted)">${t('Осталось на руки')}</div>
      <div class="tile__value">${formatMoney(netAll)}</div>
    </div>`}
  `;

  const chart = monthlyIncomeChartSVG();
  const chartSpan = window.innerWidth < 640 ? 6 : 12;
  document.getElementById('reportChart').innerHTML = chart
    ? `<div class="chartCard">
         <div class="chartCard__head">
           <span class="chartCard__title">${t('Доход по месяцам')}</span>
           <span class="chartCard__note">${t('за последние {n} месяцев', { n: chartSpan })}</span>
         </div>
         ${chart}
       </div>`
    : '';

  const rows = Array.from(byClient.values()).sort((a, b) => b.gross - a.gross);
  const tableEl = document.getElementById('reportTable');
  if (rows.length) {
    tableEl.classList.toggle('is-notax', noTax);
    tableEl.innerHTML = `
      <div class="reportTableHead">
        <span>${t('Заказчик')}</span><span>${LANG === 'en' ? t('Gross') : t('Получено')}</span>${noTax ? '' : `<span>${t('Налог')}</span><span>${t('На руки')}</span>`}
      </div>
      ${rows.map(r => `
        <div class="reportRow">
          <div>
            <div class="reportRow__name">${escapeHTML(r.name)}</div>
            <div class="reportRow__sub">${r.type === 'recurring' ? t('Постоянный') : t('Разовый')}</div>
          </div>
          <div class="reportRow__num" data-label="${LANG === 'en' ? t('Gross') : t('Получено')}">${formatMoney(r.gross)}</div>
          ${noTax ? '' : `<div class="reportRow__num" data-label="${t('Налог')}">${formatMoney(r.tax)}</div>
          <div class="reportRow__num" data-label="${t('На руки')}">${formatMoney(r.gross - r.tax)}</div>`}
        </div>
      `).join('')}
    `;
  } else if (!everReceived) {
    // Частая причина пустого отчёта: платежи есть, но ни один не отмечен полученным
    tableEl.innerHTML = emptyStateHTML(
      t('Отчёт пока пустой'),
      t('Сюда попадают только те платежи, которые вы отметили полученными. Отметьте оплату галочкой на дашборде — и суммы появятся здесь.'),
      '', ''
    );
  } else {
    tableEl.innerHTML = emptyStateHTML(
      t('За этот период поступлений не было'),
      t('Выберите другой период кнопками выше.'),
      '', ''
    );
  }
}

