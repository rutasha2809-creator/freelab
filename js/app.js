function dayStatus(dayPayments, today) {
  const allPaid = dayPayments.every(p => p.factDate);
  const anyOverdue = dayPayments.some(p => !p.factDate && p.planDate < today);
  return allPaid ? 'paid' : anyOverdue ? 'overdue' : 'pending';
}

