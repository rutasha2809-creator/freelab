// Налоговый режим пользователя: 'npd' — самозанятый РФ (4% с физлиц и 6% с юрлиц по «договору»),
// 'flat' — один свой процент со всех поступлений, 'none' — налог не считаем.
// Хранится в профиле пользователя (user_metadata.tax), поэтому одинаков на всех устройствах.
let taxSettings = { mode: 'npd', rate: 0 };

function readTaxSettings(session) {
  const meta = session && session.user && session.user.user_metadata;
  const t = meta && meta.tax;
  const mode = t && ['npd', 'flat', 'none'].includes(t.mode) ? t.mode : 'npd';
  const rate = Math.max(0, Math.min(100, Number(t && t.rate) || 0));
  taxSettings = { mode, rate };
  const cur = meta && meta.currency;
  const nextMain = CURRENCIES[cur] ? cur : 'RUB';
  if (nextMain !== mainCurrency || !viewCurrencyTouched) viewCurrency = nextMain;
  mainCurrency = nextMain;
}
let viewCurrencyTouched = false;

function taxName() { return taxSettings.mode === 'npd' ? t('Налог НПД') : t('Налог'); }

function clientTaxRatePercent(client) {
  if (!client) return 0;
  if (taxSettings.mode === 'none') return 0;
  if (taxSettings.mode === 'flat') return taxSettings.rate;
  if (!client.contract || !client.contract.enabled) return 0;
  return client.contract.payerType === 'company' ? 6 : 4;
}
function paymentTax(payment) {
  const c = getClient(payment.clientId);
  const rate = clientTaxRatePercent(c);
  return amountOf(payment) * rate / 100;
}
function paymentNet(payment) {
  return amountOf(payment) - paymentTax(payment);
}

// ---------- Производные данные: статусы и месяц ----------

function deriveStatus(payment) {
  if (payment.factDate) return 'paid';
  if (payment.planDate < todayISO()) return 'overdue';
  return 'pending';
}

// Месяц, который сейчас показывает дашборд: 0 — текущий, +1 — следующий, −1 — предыдущий.
// Его листают стрелками в календаре, и за ним следуют плитки, полоса и налоговый прогноз.
let dashboardMonthOffset = 0;

function dashboardMonth() {
  const now = new Date();
  const d = new Date(now.getFullYear(), now.getMonth() + dashboardMonthOffset, 1);
  return { year: d.getFullYear(), month: d.getMonth(), offset: dashboardMonthOffset };
}

function isInMonth(iso, year, month) {
  if (!iso) return false;
  const d = new Date(iso + 'T00:00:00');
  return d.getFullYear() === year && d.getMonth() === month;
}

function computeStats() {
  const { year, month } = dashboardMonth();
  let expected = 0, received = 0, pending = 0, overdue = 0;
  // Состав выбранного месяца — для полосы внутри главной плитки
  let monthPaid = 0, monthPending = 0, monthOverdue = 0;
  for (const p of state.payments) {
    if (!inView(p)) continue;
    const status = deriveStatus(p);
    const amount = amountOf(p);
    if (isInMonth(p.planDate, year, month)) {
      expected += amount;
      if (status === 'paid') monthPaid += amount;
      else if (status === 'overdue') monthOverdue += amount;
      else monthPending += amount;
    }
    if (status === 'paid' && isInMonth(p.factDate, year, month)) received += amount;
    if (status === 'pending' && isInMonth(p.planDate, year, month)) pending += amount;
    // Просрочку не привязываем к месяцу: долг остаётся долгом, в какой месяц ни листай
    if (status === 'overdue') overdue += amount;
  }
  return { expected, received, pending, overdue, monthPaid, monthPending, monthOverdue };
}

function computeTaxForecast() {
  const { year, month } = dashboardMonth();
  let gross = 0, tax = 0;
  for (const p of state.payments) {
    if (!inView(p)) continue;
    if (!isInMonth(p.planDate, year, month)) continue;
    const c = getClient(p.clientId);
    const rate = clientTaxRatePercent(c);
    if (!rate) continue;
    gross += amountOf(p);
    tax += paymentTax(p);
  }
  return { gross, tax, net: gross - tax };
}

